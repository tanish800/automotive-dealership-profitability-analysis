import os
import json
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

plt.switch_backend("Agg")

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHARTS_DIR = os.path.join(BASE_DIR, "outputs", "charts")
REPORTS_DIR = os.path.join(BASE_DIR, "outputs", "reports")


class WorkingCapitalModel:
    """
    Computes liquidity ratios, operating cycle metrics, and cash conversion cycles
    with strict input validation and division-by-zero safeguards.
    """

    DISCLAIMER = "ILLUSTRATIVE WORKING CAPITAL MODEL – USER-ENTERED ASSUMPTIONS"

    def __init__(
        self,
        cash_and_bank: float = 5000000.0,         # ₹50 Lakhs
        accounts_receivable: float = 10000000.0,    # ₹1.00 Crore
        inventory_value: float = 27500000.0,        # ₹2.75 Crores
        other_current_assets: float = 2500000.0,    # ₹25 Lakhs
        accounts_payable: float = 14000000.0,       # ₹1.40 Crores
        short_term_borrowings: float = 11000000.0,  # ₹1.10 Crores (floor plan line)
        other_current_liabilities: float = 3000000.0, # ₹30 Lakhs
        annual_credit_sales: float = 180000000.0,   # ₹18.00 Crores
        annual_cogs: float = 150000000.0,           # ₹15.00 Crores
        annual_credit_purchases: float = 155000000.0, # ₹15.50 Crores
        opening_inventory: float = None,
        closing_inventory: float = None,
        average_receivables: float = None,
        average_payables: float = None,
        cost_of_debt_pct: float = 10.5              # 10.5% annual floor plan interest rate
    ):
        # Validate non-negative financial inputs
        self.cash_and_bank = max(0.0, float(cash_and_bank))
        self.accounts_receivable = max(0.0, float(accounts_receivable))
        self.inventory_value = max(0.0, float(inventory_value))
        self.other_current_assets = max(0.0, float(other_current_assets))

        self.accounts_payable = max(0.0, float(accounts_payable))
        self.short_term_borrowings = max(0.0, float(short_term_borrowings))
        self.other_current_liabilities = max(0.0, float(other_current_liabilities))

        self.annual_credit_sales = max(0.0, float(annual_credit_sales))
        self.annual_cogs = max(0.0, float(annual_cogs))
        self.annual_credit_purchases = max(0.0, float(annual_credit_purchases))
        self.cost_of_debt_pct = max(0.0, float(cost_of_debt_pct))

        # Inventory averages
        self.opening_inventory = float(opening_inventory) if opening_inventory is not None else self.inventory_value
        self.closing_inventory = float(closing_inventory) if closing_inventory is not None else self.inventory_value
        self.average_inventory = (self.opening_inventory + self.closing_inventory) / 2.0

        # Payables and receivables averages
        self.average_receivables = float(average_receivables) if average_receivables is not None else self.accounts_receivable
        self.average_payables = float(average_payables) if average_payables is not None else self.accounts_payable

    def compute_all_metrics(self) -> dict:
        """Calculates all working capital and cash conversion cycle metrics."""
        current_assets = (
            self.cash_and_bank
            + self.accounts_receivable
            + self.inventory_value
            + self.other_current_assets
        )
        current_liabilities = (
            self.accounts_payable
            + self.short_term_borrowings
            + self.other_current_liabilities
        )

        nwc = current_assets - current_liabilities

        # Ratios with division-by-zero protection
        current_ratio = (current_assets / current_liabilities) if current_liabilities > 0 else np.nan
        quick_assets = current_assets - self.inventory_value
        quick_ratio = (quick_assets / current_liabilities) if current_liabilities > 0 else np.nan
        cash_ratio = (self.cash_and_bank / current_liabilities) if current_liabilities > 0 else np.nan

        # Turnover metrics
        if self.average_inventory > 0 and self.annual_cogs > 0:
            inv_turnover = self.annual_cogs / self.average_inventory
            inventory_days = (self.average_inventory / self.annual_cogs) * 365.0
        else:
            inv_turnover = 0.0
            inventory_days = 0.0

        if self.annual_credit_sales > 0:
            dso = (self.average_receivables / self.annual_credit_sales) * 365.0
        else:
            dso = 0.0

        if self.annual_credit_purchases > 0:
            dpo = (self.average_payables / self.annual_credit_purchases) * 365.0
        else:
            dpo = 0.0

        cash_conversion_cycle = inventory_days + dso - dpo
        operating_cycle = inventory_days + dso

        # Annual interest carrying cost of working capital
        annual_capital_carrying_cost = max(0.0, nwc) * (self.cost_of_debt_pct / 100.0)

        # Working capital to sales ratio
        wc_to_sales_pct = (nwc / self.annual_credit_sales * 100.0) if self.annual_credit_sales > 0 else np.nan

        return {
            "disclaimer": self.DISCLAIMER,
            "total_current_assets": round(current_assets, 2),
            "total_current_liabilities": round(current_liabilities, 2),
            "net_working_capital": round(nwc, 2),
            "current_ratio": round(current_ratio, 2) if not np.isnan(current_ratio) else "N/A",
            "quick_ratio": round(quick_ratio, 2) if not np.isnan(quick_ratio) else "N/A",
            "cash_ratio": round(cash_ratio, 2) if not np.isnan(cash_ratio) else "N/A",
            "average_inventory": round(self.average_inventory, 2),
            "inventory_turnover": round(inv_turnover, 2),
            "inventory_days_dsi": round(inventory_days, 1),
            "days_sales_outstanding_dso": round(dso, 1),
            "days_payable_outstanding_dpo": round(dpo, 1),
            "operating_cycle_days": round(operating_cycle, 1),
            "cash_conversion_cycle_days": round(cash_conversion_cycle, 1),
            "annual_carrying_cost_inr": round(annual_capital_carrying_cost, 2),
            "wc_to_sales_pct": round(wc_to_sales_pct, 2) if not np.isnan(wc_to_sales_pct) else "N/A",
        }


def get_industry_benchmark_scenarios() -> dict[str, WorkingCapitalModel]:
    """
    Returns 3 standardized automotive dealership operating scenarios:
    1. Base Case: Typical mid-sized multi-brand dealership
    2. Lean Optimized: High inventory velocity, disciplined collections, OEM-supported payables
    3. Stressed / Illiquid: Accumulation of aging lot vehicles, sluggish debtor collections
    """
    base_case = WorkingCapitalModel(
        cash_and_bank=5000000,
        accounts_receivable=10000000,
        inventory_value=27500000,
        other_current_assets=2500000,
        accounts_payable=14000000,
        short_term_borrowings=11000000,
        other_current_liabilities=3000000,
        annual_credit_sales=180000000,
        annual_cogs=150000000,
        annual_credit_purchases=155000000,
    )

    lean_case = WorkingCapitalModel(
        cash_and_bank=8000000,
        accounts_receivable=6000000,
        inventory_value=16000000,      # Lean fast-turn lot (38 days)
        other_current_assets=2000000,
        accounts_payable=18000000,      # Negotiated 42 days vendor terms
        short_term_borrowings=5000000,  # Lower debt burden
        other_current_liabilities=2000000,
        annual_credit_sales=180000000,
        annual_cogs=150000000,
        annual_credit_purchases=155000000,
    )

    stressed_case = WorkingCapitalModel(
        cash_and_bank=2000000,
        accounts_receivable=17500000,   # Slow recovery / debtor lag (35 days)
        inventory_value=35000000,      # Aged vehicles stuck on lot (85 days)
        other_current_assets=3500000,
        accounts_payable=9500000,       # Compressed supplier credit (22 days)
        short_term_borrowings=20000000, # Heavy floor-plan interest trap
        other_current_liabilities=4500000,
        annual_credit_sales=180000000,
        annual_cogs=150000000,
        annual_credit_purchases=155000000,
    )

    return {
        "Base Case (Standard Dealership)": base_case,
        "Lean Optimized (Fast Velocity)": lean_case,
        "Stressed (High Lot Aging)": stressed_case,
    }


def compare_scenarios() -> pd.DataFrame:
    """Generates comparative dataframe of scenario performance."""
    scenarios = get_industry_benchmark_scenarios()
    rows = []
    for name, model in scenarios.items():
        metrics = model.compute_all_metrics()
        rows.append({
            "Scenario": name,
            "Current Assets (₹ Cr)": round(metrics["total_current_assets"] / 10000000, 2),
            "Current Liabilities (₹ Cr)": round(metrics["total_current_liabilities"] / 10000000, 2),
            "Net Working Capital (₹ Cr)": round(metrics["net_working_capital"] / 10000000, 2),
            "Current Ratio": metrics["current_ratio"],
            "Quick Ratio": metrics["quick_ratio"],
            "Inventory Turnover (x)": metrics["inventory_turnover"],
            "Inventory Days (DSI)": metrics["inventory_days_dsi"],
            "DSO (Days)": metrics["days_sales_outstanding_dso"],
            "DPO (Days)": metrics["days_payable_outstanding_dpo"],
            "Cash Conversion Cycle (Days)": metrics["cash_conversion_cycle_days"],
            "Carrying Cost @ 10.5% (₹ Lakhs)": round(metrics["annual_carrying_cost_inr"] / 100000, 2),
        })
    return pd.DataFrame(rows)


def plot_working_capital_visualizations(comparison_df: pd.DataFrame) -> str:
    """Visualizes Cash Conversion Cycle bridge and Liquidity Ratios across scenarios."""
    os.makedirs(CHARTS_DIR, exist_ok=True)
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(15, 6))

    scenarios = ["Base Case", "Lean Optimized", "Stressed"]
    dsi = comparison_df["Inventory Days (DSI)"].values
    dso = comparison_df["DSO (Days)"].values
    dpo = comparison_df["DPO (Days)"].values
    ccc = comparison_df["Cash Conversion Cycle (Days)"].values

    x = np.arange(len(scenarios))
    w = 0.2
    ax1.bar(x - 1.5*w, dsi, w, label="Inventory Days (DSI)", color="#2C3E50")
    ax1.bar(x - 0.5*w, dso, w, label="Debtor Days (DSO)", color="#2980B9")
    ax1.bar(x + 0.5*w, dpo, w, label="Creditor Days (DPO)", color="#E74C3C")
    ax1.bar(x + 1.5*w, ccc, w, label="Cash Conversion Cycle (CCC)", color="#27AE60")

    ax1.set_xticks(x)
    ax1.set_xticklabels(scenarios)
    ax1.set_ylabel("Operating Cycle Days")
    ax1.set_title("Cash Conversion Cycle Breakdown by Scenario", pad=15)
    ax1.legend(frameon=True)
    ax1.grid(True, linestyle=":", alpha=0.5)

    cr = comparison_df["Current Ratio"].values
    qr = comparison_df["Quick Ratio"].values

    x2 = np.arange(len(scenarios))
    w2 = 0.35
    ax2.bar(x2 - w2/2, cr, w2, label="Current Ratio", color="#1F4E79")
    ax2.bar(x2 + w2/2, qr, w2, label="Quick Ratio", color="#5B9BD5")
    ax2.axhline(1.5, color="#27AE60", linestyle="--", linewidth=1.5, label="Target CR (1.5x)")
    ax2.axhline(1.0, color="#E67E22", linestyle=":", linewidth=1.5, label="Target QR (1.0x)")

    ax2.set_xticks(x2)
    ax2.set_xticklabels(scenarios)
    ax2.set_ylabel("Ratio Multiple")
    ax2.set_title("Liquidity Cushion: Current vs. Quick Ratio", pad=15)
    ax2.legend(frameon=True)
    ax2.grid(True, linestyle=":", alpha=0.5)

    fig.suptitle("WORKING CAPITAL & CASH CONVERSION CYCLE (HYPOTHETICAL DEALERSHIP SCENARIOS)", fontsize=14, fontweight="bold", y=0.98)
    plt.tight_layout()
    chart_path = os.path.join(CHARTS_DIR, "working_capital_analysis.png")
    fig.savefig(chart_path, dpi=300)
    plt.close(fig)
    print(f"[WORKING CAPITAL] Visualization saved to: {chart_path}")
    return chart_path


def run_working_capital_analysis() -> dict:
    """Executes full working capital simulation and writes report."""
    comp_df = compare_scenarios()
    chart_file = plot_working_capital_visualizations(comp_df)

    scenarios = get_industry_benchmark_scenarios()
    full_output = {
        "disclaimer": WorkingCapitalModel.DISCLAIMER,
        "scenarios": {k: m.compute_all_metrics() for k, m in scenarios.items()},
        "comparison_table": comp_df.to_dict(orient="records"),
        "chart_path": chart_file,
    }

    os.makedirs(REPORTS_DIR, exist_ok=True)
    summary_path = os.path.join(REPORTS_DIR, "working_capital_summary.json")
    with open(summary_path, "w", encoding="utf-8") as f:
        json.dump(full_output, f, indent=4)

    print(f"[WORKING CAPITAL] Simulation complete. Summary saved to: {summary_path}")
    return full_output


if __name__ == "__main__":
    run_working_capital_analysis()
