import os
import json
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

plt.switch_backend("Agg")

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROCESSED_DATA_PATH = os.path.join(BASE_DIR, "data", "processed", "cleaned_vehicle_data.csv")
CHARTS_DIR = os.path.join(BASE_DIR, "outputs", "charts")
REPORTS_DIR = os.path.join(BASE_DIR, "outputs", "reports")


class ProfitabilityScenarioModel:
    """
    Simulates dealership vehicle-level unit economics, gross margins,
    and net operating contributions across configurable operational scenarios.
    """

    DEFAULT_ASSUMPTIONS = {
        "acquisition_cost_pct": 0.82,       # 82% of list price assumed acquisition buy-in (18% initial spread)
        "discount_pct": 0.04,               # 4% anticipated negotiation markdown at final closing
        "reconditioning_cost": 15000.0,     # ₹15,000 average mechanical & cosmetic refurbishment
        "transportation_cost": 5000.0,      # ₹5,000 regional logistics / flatbed transport
        "other_selling_costs": 8000.0,      # ₹8,000 documentation, sales commission, detailing
    }

    DISCLAIMER_LABEL = "HYPOTHETICAL FINANCIAL SCENARIO – NOT ACTUAL DEALERSHIP ACCOUNTING DATA"

    def __init__(self, assumptions: dict = None):
        self.assumptions = self.DEFAULT_ASSUMPTIONS.copy()
        if assumptions:
            self.assumptions.update(assumptions)

    def calculate_vehicle_profitability(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Applies unit economics scenario assumptions to the real vehicle listings.
        """
        acq_pct = self.assumptions["acquisition_cost_pct"]
        disc_pct = self.assumptions["discount_pct"]
        recond = self.assumptions["reconditioning_cost"]
        trans = self.assumptions["transportation_cost"]
        other_costs = self.assumptions["other_selling_costs"]

        df_scenario = df.copy()

        # Scenario Revenue & Cost Derivations
        df_scenario["Scenario_Expected_Selling_Price"] = df_scenario["selling_price"].astype(float)
        df_scenario["Scenario_Discount"] = df_scenario["Scenario_Expected_Selling_Price"] * disc_pct
        df_scenario["Scenario_Revenue"] = df_scenario["Scenario_Expected_Selling_Price"] - df_scenario["Scenario_Discount"]

        df_scenario["Scenario_Acquisition_Cost"] = df_scenario["Scenario_Expected_Selling_Price"] * acq_pct
        df_scenario["Scenario_Gross_Profit"] = df_scenario["Scenario_Revenue"] - df_scenario["Scenario_Acquisition_Cost"]

        # Safe gross margin calculation
        df_scenario["Scenario_Gross_Margin_Pct"] = np.where(
            df_scenario["Scenario_Revenue"] > 0,
            (df_scenario["Scenario_Gross_Profit"] / df_scenario["Scenario_Revenue"]) * 100.0,
            0.0
        )

        df_scenario["Scenario_Reconditioning_Cost"] = recond
        df_scenario["Scenario_Transportation_Cost"] = trans
        df_scenario["Scenario_Other_Selling_Costs"] = other_costs
        df_scenario["Scenario_Total_Direct_Costs"] = recond + trans + other_costs

        df_scenario["Scenario_Net_Contribution"] = (
            df_scenario["Scenario_Gross_Profit"] - df_scenario["Scenario_Total_Direct_Costs"]
        )

        df_scenario["Scenario_Net_Margin_Pct"] = np.where(
            df_scenario["Scenario_Revenue"] > 0,
            (df_scenario["Scenario_Net_Contribution"] / df_scenario["Scenario_Revenue"]) * 100.0,
            0.0
        )

        df_scenario["Scenario_Data_Classification"] = self.DISCLAIMER_LABEL
        return df_scenario

    def summarize_brand_profitability(self, df_scenario: pd.DataFrame, top_n: int = 15) -> pd.DataFrame:
        """Aggregates unit economics by automotive brand."""
        brand_summary = df_scenario.groupby("Vehicle_Brand").agg(
            listing_count=("Scenario_Revenue", "count"),
            total_scenario_revenue=("Scenario_Revenue", "sum"),
            total_scenario_gross_profit=("Scenario_Gross_Profit", "sum"),
            total_scenario_net_contribution=("Scenario_Net_Contribution", "sum"),
            avg_gross_profit_per_unit=("Scenario_Gross_Profit", "mean"),
            avg_net_contribution_per_unit=("Scenario_Net_Contribution", "mean"),
        ).reset_index()

        brand_summary["scenario_gross_margin_pct"] = (
            brand_summary["total_scenario_gross_profit"] / brand_summary["total_scenario_revenue"]
        ) * 100.0
        brand_summary["scenario_net_margin_pct"] = (
            brand_summary["total_scenario_net_contribution"] / brand_summary["total_scenario_revenue"]
        ) * 100.0

        brand_summary = brand_summary.sort_values(by="total_scenario_revenue", ascending=False).head(top_n).reset_index(drop=True)
        return brand_summary

    def summarize_price_category_profitability(self, df_scenario: pd.DataFrame) -> pd.DataFrame:
        """Aggregates scenario margins across price tiers."""
        cat_summary = df_scenario.groupby("Price_Category").agg(
            unit_count=("Scenario_Revenue", "count"),
            total_scenario_revenue=("Scenario_Revenue", "sum"),
            total_scenario_gross_profit=("Scenario_Gross_Profit", "sum"),
            total_scenario_net_contribution=("Scenario_Net_Contribution", "sum"),
            avg_gross_profit_per_unit=("Scenario_Gross_Profit", "mean"),
            avg_net_contribution_per_unit=("Scenario_Net_Contribution", "mean"),
        ).reset_index()

        cat_summary["scenario_gross_margin_pct"] = (
            cat_summary["total_scenario_gross_profit"] / cat_summary["total_scenario_revenue"]
        ) * 100.0
        cat_summary["scenario_net_margin_pct"] = (
            cat_summary["total_scenario_net_contribution"] / cat_summary["total_scenario_revenue"]
        ) * 100.0

        order = ["Budget (< ₹3L)", "Mid-Range (₹3L - ₹6L)", "Upper Mid-Range (₹6L - ₹10L)", "Premium (₹10L - ₹20L)", "Luxury (> ₹20L)"]
        cat_summary["sort_key"] = cat_summary["Price_Category"].map({c: i for i, c in enumerate(order)})
        return cat_summary.sort_values("sort_key").drop(columns=["sort_key"]).reset_index(drop=True)

    def run_sensitivity_grid(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Computes scenario portfolio gross profit across varying acquisition costs and discount buffers.
        """
        acq_rates = [0.78, 0.80, 0.82, 0.84, 0.86]
        disc_rates = [0.02, 0.04, 0.06, 0.08]

        total_list_value = df["selling_price"].sum()
        results = []
        for acq in acq_rates:
            for disc in disc_rates:
                revenue = total_list_value * (1.0 - disc)
                cogs = total_list_value * acq
                gross_profit = revenue - cogs
                gross_margin = (gross_profit / revenue) * 100.0
                results.append({
                    "Acquisition_Cost_Pct": f"{acq*100:.0f}%",
                    "Discount_Pct": f"{disc*100:.0f}%",
                    "Portfolio_Scenario_Revenue_Cr": round(revenue / 10000000, 2),
                    "Portfolio_Scenario_Gross_Profit_Cr": round(gross_profit / 10000000, 2),
                    "Portfolio_Scenario_Gross_Margin_Pct": round(gross_margin, 2),
                })
        return pd.DataFrame(results)


def plot_scenario_visualizations(brand_summary: pd.DataFrame, cat_summary: pd.DataFrame) -> str:
    """Creates presentation chart for scenario gross profit and net contribution."""
    os.makedirs(CHARTS_DIR, exist_ok=True)
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(15, 6))

    # Ax 1: Brand Gross Profit vs Net Contribution (Crores)
    top10 = brand_summary.head(10).copy()
    x = np.arange(len(top10))
    width = 0.38
    ax1.bar(x - width/2, top10["total_scenario_gross_profit"] / 10000000, width, label="Scenario Gross Profit", color="#1F4E79")
    ax1.bar(x + width/2, top10["total_scenario_net_contribution"] / 10000000, width, label="Scenario Net Contribution", color="#27AE60")
    ax1.set_xticks(x)
    ax1.set_xticklabels(top10["Vehicle_Brand"], rotation=35, ha="right")
    ax1.set_ylabel("Scenario Profit (₹ Crores)")
    ax1.set_title("Hypothetical Brand Profitability (Top 10 Volume Brands)", pad=15)
    ax1.legend(frameon=True)

    # Ax 2: Net Contribution Margin % by Price Tier
    bars = ax2.bar(cat_summary["Price_Category"], cat_summary["scenario_net_margin_pct"], color="#E67E22", edgecolor="#B95C00", alpha=0.85)
    ax2.set_title("Scenario Net Contribution Margin % by Price Tier", pad=15)
    ax2.set_ylabel("Net Contribution Margin (%)")
    ax2.set_xticklabels(cat_summary["Price_Category"], rotation=25, ha="right")
    for bar in bars:
        h = bar.get_height()
        ax2.text(bar.get_x() + bar.get_width() / 2, h + 0.3, f"{h:.1f}%", ha="center", fontsize=9, fontweight="bold")

    fig.suptitle("DEALERSHIP SCENARIO UNIT ECONOMICS (HYPOTHETICAL FINANCIAL MODEL)", fontsize=14, fontweight="bold", y=0.98)
    plt.tight_layout()
    chart_path = os.path.join(CHARTS_DIR, "scenario_profitability_analysis.png")
    fig.savefig(chart_path, dpi=300)
    plt.close(fig)
    print(f"[PROFITABILITY SCENARIO] Visualization saved to: {chart_path}")
    return chart_path


def run_full_profitability_scenario() -> dict:
    """Executes full unit economics scenario modeling and persists results."""
    df = pd.read_csv(PROCESSED_DATA_PATH)
    model = ProfitabilityScenarioModel()
    df_scenario = model.calculate_vehicle_profitability(df)
    brand_perf = model.summarize_brand_profitability(df_scenario)
    cat_perf = model.summarize_price_category_profitability(df_scenario)
    sensitivity = model.run_sensitivity_grid(df)
    chart_file = plot_scenario_visualizations(brand_perf, cat_perf)

    # Key aggregated portfolio scenario metrics
    total_revenue = float(df_scenario["Scenario_Revenue"].sum())
    total_cogs = float(df_scenario["Scenario_Acquisition_Cost"].sum())
    total_gp = float(df_scenario["Scenario_Gross_Profit"].sum())
    total_net_contrib = float(df_scenario["Scenario_Net_Contribution"].sum())
    portfolio_gm_pct = float((total_gp / total_revenue) * 100.0) if total_revenue > 0 else 0.0
    portfolio_net_pct = float((total_net_contrib / total_revenue) * 100.0) if total_revenue > 0 else 0.0

    summary = {
        "disclaimer": ProfitabilityScenarioModel.DISCLAIMER_LABEL,
        "assumptions": model.assumptions,
        "portfolio_totals": {
            "total_scenario_revenue_inr": total_revenue,
            "total_scenario_acquisition_cost_inr": total_cogs,
            "total_scenario_gross_profit_inr": total_gp,
            "total_scenario_net_contribution_inr": total_net_contrib,
            "portfolio_gross_margin_pct": round(portfolio_gm_pct, 2),
            "portfolio_net_contribution_margin_pct": round(portfolio_net_pct, 2),
            "avg_gross_profit_per_unit_inr": round(float(df_scenario["Scenario_Gross_Profit"].mean()), 2),
            "avg_net_contribution_per_unit_inr": round(float(df_scenario["Scenario_Net_Contribution"].mean()), 2),
        },
        "brand_summary": brand_perf.to_dict(orient="records"),
        "category_summary": cat_perf.to_dict(orient="records"),
        "sensitivity_matrix": sensitivity.to_dict(orient="records"),
        "chart_path": chart_file,
    }

    os.makedirs(REPORTS_DIR, exist_ok=True)
    summary_path = os.path.join(REPORTS_DIR, "profitability_scenario_summary.json")
    with open(summary_path, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=4)

    print(f"[PROFITABILITY SCENARIO] Scenario modeling complete. Summary saved to: {summary_path}")
    return summary


if __name__ == "__main__":
    run_full_profitability_scenario()
